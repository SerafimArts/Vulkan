<?php

declare(strict_types=1);

namespace Serafim\Vulkan\Build\Generator\Emitter;

use Serafim\Vulkan\Build\Generator\Registry\Constant;

/**
 * Writes the `#define` constants of the specification as the constants of the
 * root namespace.
 *
 * @internal this is an internal library class, please do not use it in your code
 * @psalm-internal Serafim\Vulkan\Build
 */
final readonly class ConstantsEmitter
{
    /**
     * @param list<Constant> $constants
     */
    public function emit(array $constants): GeneratedFile
    {
        $lines = [
            '<?php',
            '',
            '/**',
            ' * This file is generated by `bin/vulkan generate`, do not edit it by hand.',
            ' */',
            '',
            'declare(strict_types=1);',
            '',
            'namespace ' . Locations::ROOT_NAMESPACE . ';',
        ];

        foreach ($constants as $constant) {
            $description = ['`' . $constant->definition . '`'];

            if ($constant->comment !== null) {
                $description = [...DocComments::createLines($constant->comment), '', ...$description];
            }

            $lines[] = '';
            $lines[] = '/**';

            foreach ($description as $line) {
                $lines[] = \rtrim(' * ' . $line);
            }

            $lines[] = ' */';
            $lines[] = 'const ' . $constant->name . ' = ' . $constant->expression . ';';
        }

        return new GeneratedFile('constants.php', \implode("\n", $lines) . "\n");
    }
}
