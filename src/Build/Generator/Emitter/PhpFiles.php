<?php

declare(strict_types=1);

namespace Serafim\Vulkan\Build\Generator\Emitter;

use Nette\PhpGenerator\PhpFile;
use Nette\PhpGenerator\PsrPrinter;

/**
 * Creates and prints the files of the generated classes.
 *
 * @internal this is an internal library class, please do not use it in your code
 * @psalm-internal Serafim\Vulkan\Build
 */
final readonly class PhpFiles
{
    public function create(): PhpFile
    {
        $file = new PhpFile();

        $file->setStrictTypes();
        $file->addComment('This file is generated by `bin/vulkan generate`, do not edit it by hand.');

        return $file;
    }

    public function print(PhpFile $file): string
    {
        return new PsrPrinter()->printFile($file);
    }
}
