<?php

declare(strict_types=1);

namespace Serafim\Vulkan\Build\Generator\Emitter;

use Serafim\Vulkan\Build\Generator\Registry\Registry;
use Serafim\Vulkan\VulkanBase;

/**
 * Writes `.phpstorm.meta.php`: the bits of flags that the arguments of the
 * commands and of the structures can be made of, and the types that the
 * structures return by the class of the chain.
 *
 * @internal this is an internal library class, please do not use it in your code
 * @psalm-internal Serafim\Vulkan\Build
 */
final readonly class MetaEmitter
{
    public function __construct(
        private Registry $registry,
    ) {}

    public function emit(MetaRecorder $recorder): GeneratedFile
    {
        $arguments = $recorder->getArguments();
        $used = [];

        foreach ($arguments as $methods) {
            foreach ($methods as $indexes) {
                foreach ($indexes as $bits) {
                    $used[$bits] = true;
                }
            }
        }

        \ksort($used);

        $lines = [
            '<?php',
            '',
            '// This file is generated by `bin/vulkan generate`, do not edit it by hand.',
            '',
            'namespace PHPSTORM_META {',
        ];

        foreach (\array_keys($used) as $bits) {
            $constants = $this->createConstants($bits);

            if ($constants === []) {
                continue;
            }

            $lines[] = "    registerArgumentsSet('" . $bits . "',";

            foreach ($constants as $constant) {
                $lines[] = '        ' . $constant . ',';
            }

            $lines[] = '    );';
        }

        \ksort($arguments);

        foreach ($arguments as $class => $methods) {
            \ksort($methods);

            foreach ($methods as $method => $indexes) {
                \ksort($indexes);

                foreach ($indexes as $index => $bits) {
                    if ($this->createConstants($bits) !== []) {
                        $lines[] = '    expectedArguments(' . $this->createClass($class) . '::' . $method . '(), '
                            . $index . ", argumentsSet('" . $bits . "'));";
                    }
                }
            }
        }

        $finders = $recorder->getFinders();

        \sort($finders);

        foreach ($finders as $class) {
            $lines[] = '    override(' . $this->createClass($class) . '::findChained(0), type(0));';
        }

        $commands = $this->createCommands();

        $lines[] = '    registerArgumentsSet(\'VulkanCommands\',';

        foreach ($commands as $command) {
            $lines[] = "        '" . $command . "',";
        }

        $lines[] = '    );';
        $lines[] = '    expectedArguments(' . $this->createClass(VulkanBase::class) . '::vkGetInstanceProc(), 0, '
            . "argumentsSet('VulkanCommands'));";
        $lines[] = '    expectedArguments(' . $this->createClass(Locations::createClassName(Locations::ROOT_NAMESPACE, 'Vulkan')) . '::vkGetInstanceProcAddr(), 0, '
            . "argumentsSet('VulkanCommands'));";
        $lines[] = '}';

        return new GeneratedFile('../resources/.phpstorm.meta.php', \implode("\n", $lines) . "\n");
    }

    /**
     * Returns the names of the commands, and of their aliases, that the
     * headers declare.
     *
     * @return list<non-empty-string>
     */
    private function createCommands(): array
    {
        $names = [];

        foreach ($this->registry->getCommands() as $command) {
            if (!$this->registry->isDeclared('PFN_' . $command->name)) {
                continue;
            }

            $names[] = $command->name;

            foreach ($this->registry->findAliases($command->name) as $alias) {
                $names[] = $alias;
            }
        }

        \sort($names);

        return $names;
    }

    /**
     * Returns the constants of the type of the bits.
     *
     * @return list<string>
     */
    private function createConstants(string $bits): array
    {
        $grouped = [];

        foreach ($this->registry->getDefines() as $define) {
            if ($define->group === $bits) {
                $grouped[] = $this->createClass(Locations::createClassName(Locations::ROOT_NAMESPACE, $define->name));
            }
        }

        if ($grouped !== []) {
            return $grouped;
        }

        $enum = $this->registry->findEnum($bits);

        if ($enum === null) {
            return [];
        }

        $names = [...\array_keys($enum->cases), ...\array_keys($enum->aliases)];
        $constants = [];

        foreach ($names as $name) {
            $constants[] = $this->createClass(Locations::createClassName(Locations::ENUM_NAMESPACE, $bits)) . '::' . $name;
        }

        return $constants;
    }

    private function createClass(string $class): string
    {
        return '\\' . $class;
    }
}
